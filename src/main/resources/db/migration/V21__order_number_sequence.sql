-- Последовательность для генерации номеров заказов.
--
-- Номер заказа уникален, и раньше уникальность обеспечивалась двумя случайными
-- цифрами: yyMMddHHmm + userId + random(00..99). На два заказа одного
-- пользователя в пределах одной минуты это 1% коллизий, а коллизия ловится
-- только UNIQUE-ограничением — то есть клиент получал 500 на оформлении
-- заказа. Именно это было причиной изредка падающего OrderServiceTest.
--
-- Теперь последние четыре цифры номера берутся из этой последовательности, то
-- есть уникальность гарантирует сама база. Это не зависит от того, на каком
-- инстансе приложения считается номер, и не ослабевает при нескольких
-- репликах.
--
-- Номер: yyMMddHHmm (10) + userId % 10000 (4) + nextval % 10000 (4) = 18 цифр.
-- Граница: совпадение возможно, только если один пользователь оформит 10 000
-- заказов в одну минуту.
--
-- Пропуски в номерах возможны: nextval расходует значение даже при откате
-- транзакции. Для номеров заказов это неважно.

CREATE SEQUENCE IF NOT EXISTS order_number_seq AS bigint START WITH 1 INCREMENT BY 1;
