-- Полнотекстовая статистика запросов.
--
-- Расширение собирает то, чего не давал диагностический скрипт: реальные
-- счётчики и планы по каждому запросу, включая те, что приходят с
-- бинд-параметрами от приложения. По скрипту такой запрос выглядел как
-- «последовательный скан», хотя на самом деле это один и тот же запрос,
-- выполняемый Hibernate.
--
-- Требует pg_stat_statements в shared_preload_libraries — это задано в
-- docker-compose.yml, иначе представление pg_stat_statements будет пустым,
-- а обращения к нему — падать с ошибкой.
--
-- pg_stat_statements — trusted extension: суперпользователь не нужен,
-- достаточно прав на базу. Отдельный рестарт Postgres не требуется, деплой
-- пересоздаёт контейнеры в любом случае.

CREATE EXTENSION IF NOT EXISTS pg_stat_statements;
